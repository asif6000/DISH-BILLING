const dicts: Record<Lang, Record<string, string>> = { bn, en }

interface I18nCtx { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string }
const Ctx = createContext<I18nCtx>({ lang: 'bn', setLang: () => {}, t: (k) => k })

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem('ava_lang') as Lang) || 'bn')
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    localStorage.setItem('ava_lang', l)
  }, [])
  const t = useCallback((k: string) => dicts[lang][k] || dicts.en[k] || k, [lang])
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useI18n() { return useContext(Ctx) }

export const MONTHS_BN = ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর']
export const MONTHS_EN = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']

export function monthLabel(ym: string, lang: Lang): string {
  const [y, m] = ym.split('-').map(Number)
  const names = lang === 'bn' ? MONTHS_BN : MONTHS_EN
  return `${names[(m || 1) - 1]} ${y}`
}
